const dir = path.join(__dirname, '../node_modules/lucide-react/dist/esm/icons');
const svg = (name) => {
    let source = fs.readFileSync(path.join(dir, name + '.mjs'), 'utf8');
    // Some icons are aliases of another file.
    const alias = /export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/.exec(source);
    if (alias) {
        return svg(alias[1]);
    }
    // Take the array literal after "node:" by counting brackets.
    const start = source.indexOf('[', source.indexOf('node:'));
    let depth = 0;
    let end = start;
    for (; end < source.length; end++) {
        if (source[end] === '[') depth++;
        if (source[end] === ']' && --depth === 0) break;
    }
    const node = new Function('return ' + source.slice(start, end + 1))();
    const inner = node
        .map(([tag, attrs]) => {
            const { key, ...rest } = attrs;

            return `<${tag} ${Object.entries(rest).map(([k, v]) => `${k}='${v}'`).join(' ')}/>`;
        })
        .join('');

    return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'>${inner}</svg>`;
};

